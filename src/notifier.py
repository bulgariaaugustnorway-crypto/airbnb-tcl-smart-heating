def redact_sensitive_str(text: str, secret: Optional[str] = None) -> str:
    """
    Scrub sensitive bot tokens or URLs containing bot tokens from any text.
    Protects bot tokens in logs, exception traces, URLs, and dashboard displays.
    """
    if not text:
        return ""
    res = str(text)
    if secret and len(secret) >= 4:
        res = res.replace(secret, "[REDACTED_BOT_TOKEN]")
    # Redact Telegram bot URL patterns: https://api.telegram.org/bot<TOKEN>/...
    res = re.sub(r'(https?://api\.telegram\.org/bot)[^/\s?#]+', r'\1[REDACTED_TOKEN]', res)
    # Redact query parameters like bot_token=... or token=...
    res = re.sub(r'([?&](?:bot_)?token=)[^&\s]+', r'\1[REDACTED_TOKEN]', res)
    return res


def format_device_label(device_id: str, config: Optional[AutomationConfig] = None) -> str:
    """Format physical hardware device ID into a human-readable room name."""
    cfg = config or AutomationConfig
    lr_id = getattr(cfg, "TCL_LIVING_ROOM_ID", "demo_living_room")
    br_id = getattr(cfg, "TCL_BEDROOM_ID", "demo_bedroom")
    if device_id == lr_id:
        return f"Living Room ({device_id})"
    elif device_id == br_id:
        return f"Bedroom ({device_id})"
    return f"AC Unit ({device_id})"


class NotificationEvent:
    """Represents an alert or event generated by the automation."""
    def __init__(
        self,
        event_type: str,
        title: str,
        message: str,
        severity: str = "INFO",
        metadata: Optional[Dict[str, Any]] = None,
        timestamp: Optional[datetime] = None
    ):
        self.event_type = event_type
        self.title = title
        self.message = message
        self.severity = severity.upper()  # INFO, WARNING, ERROR, CRITICAL
        self.metadata = metadata or {}
        self.timestamp = timestamp or datetime.now()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "timestamp": self.timestamp.isoformat(),
            "event_type": self.event_type,
            "severity": self.severity,
            "title": self.title,
            "message": self.message,
            "metadata": self.metadata
        }


class TelegramDeliveryAdapter:
    """
    Secure delivery adapter for Telegram Bot API sendMessage.
    Handles token redaction, response validation, HTTP 429 rate limit parameters,
    timeouts, and bounded retries with backoff.
    """
    def __init__(
        self,
        bot_token: Optional[str] = None,
        chat_id: Optional[str] = None,
        timeout: float = 5.0,
        max_retries: int = 2,
        backoff_seconds: float = 1.0,
    ):
        self.bot_token = bot_token.strip() if bot_token else None
        self.chat_id = str(chat_id).strip() if chat_id else None
        self.timeout = timeout
        self.max_retries = max_retries
        self.backoff_seconds = backoff_seconds

    @property
    def is_configured(self) -> bool:
        return bool(self.bot_token and self.chat_id)

    def send_message(self, text: str, parse_mode: Optional[str] = "Markdown") -> Tuple[bool, Optional[str]]:
        """
        Send a message via Telegram Bot API sendMessage.
        Returns:
            (success: bool, error_description: Optional[str])
        """
        if not self.is_configured:
            return (False, "Telegram not configured: missing bot token or chat ID")

        url = f"https://api.telegram.org/bot{self.bot_token}/sendMessage"
        sanitized_url = redact_sensitive_str(url, self.bot_token)

        payload_dict: Dict[str, Any] = {
            "chat_id": self.chat_id,
            "text": text,
        }
        if parse_mode:
            payload_dict["parse_mode"] = parse_mode

        payload_bytes = json.dumps(payload_dict).encode("utf-8")

        for attempt in range(self.max_retries + 1):
            req = urllib.request.Request(
                url,
                data=payload_bytes,
                headers={"Content-Type": "application/json"}
            )
            try:
                with http_transport.open_https(req, timeout=self.timeout) as resp:
                    resp_body = resp.read().decode("utf-8", errors="ignore")
                    try:
                        data = json.loads(resp_body)
                    except Exception:
                        data = {}

                    if 200 <= resp.status < 300 and data.get("ok") is True:
                        return (True, None)

                    err_desc = data.get("description", f"Telegram API error (status {resp.status})")
                    sanitized_err = redact_sensitive_str(err_desc, self.bot_token)
                    _LOGGER.warning(
                        f"Telegram API delivery failed to {sanitized_url}: {sanitized_err}"
                    )
                    return (False, sanitized_err)

            except urllib.error.HTTPError as he:
                raw_body = he.read().decode("utf-8", errors="ignore")
                retry_after = None
                try:
                    err_json = json.loads(raw_body)
                    err_desc = err_json.get("description", str(he))
                    retry_after = err_json.get("parameters", {}).get("retry_after")
                except Exception:
                    err_desc = str(he)

                sanitized_err = redact_sensitive_str(err_desc, self.bot_token)

                # 401/403: Authentication or Authorization error - do NOT retry
                if he.code in (401, 403):
                    _LOGGER.error(f"Telegram delivery rejected HTTP {he.code}: {sanitized_err}")
                    return (False, f"HTTP {he.code}: {sanitized_err}")

                # 400: If markdown entity parsing failed, retry once with plain text
                if he.code == 400 and parse_mode and "can't parse entities" in err_desc.lower():
                    _LOGGER.warning("Telegram parse_mode markdown rejected; retrying with plain text")
                    return self.send_message(text, parse_mode=None)

                # 429: Rate Limit
                if he.code == 429:
                    _LOGGER.warning(f"Telegram rate limited (HTTP 429, retry_after={retry_after}): {sanitized_err}")
                    if attempt < self.max_retries and retry_after is not None and retry_after <= 2.0:
                        time.sleep(retry_after)
                        continue
                    return (False, f"HTTP 429 Rate Limit (retry_after={retry_after}): {sanitized_err}")

                # Other HTTP errors (5xx, etc.)
                _LOGGER.warning(f"Telegram HTTP {he.code} (attempt {attempt+1}/{self.max_retries+1}): {sanitized_err}")
                if attempt < self.max_retries:
                    if self.backoff_seconds > 0:
                        time.sleep(self.backoff_seconds * (2 ** attempt))
                    continue
                return (False, f"HTTP {he.code}: {sanitized_err}")

            except (urllib.error.URLError, TimeoutError, socket.timeout) as te:
                sanitized_err = redact_sensitive_str(str(te), self.bot_token)
                _LOGGER.warning(f"Telegram network error (attempt {attempt+1}/{self.max_retries+1}): {sanitized_err}")
                if attempt < self.max_retries:
                    if self.backoff_seconds > 0:
                        time.sleep(self.backoff_seconds * (2 ** attempt))
                    continue
                return (False, f"Network timeout/error: {sanitized_err}")

            except Exception as e:
                sanitized_err = redact_sensitive_str(str(e), self.bot_token)
                _LOGGER.error(f"Unexpected Telegram dispatch error: {sanitized_err}")
                return (False, f"Unexpected error: {sanitized_err}")

        return (False, "Telegram delivery exceeded maximum retries")


class NotificationDispatcher:
    """
    Dispatches notifications to multiple destinations:
    Console, Structured Audit Log, Telegram Bot API, and Webhooks.
    Includes rate limiting, duplicate suppression, severity escalation, and delivery state tracking.
    """

    def __init__(
        self,
        webhook_url: Optional[str] = None,
        bot_token: Optional[str] = None,
        chat_id: Optional[str] = None,
        config: Optional[AutomationConfig] = None
    ):
        self.config = config or AutomationConfig()
        self.webhook_url = webhook_url or getattr(self.config, "NOTIFICATION_WEBHOOK_URL", None)
        self.bot_token = bot_token or getattr(self.config, "TELEGRAM_BOT_TOKEN", None)
        self.chat_id = chat_id or getattr(self.config, "TELEGRAM_CHAT_ID", None)

        self.telegram_adapter = TelegramDeliveryAdapter(
            bot_token=self.bot_token,
            chat_id=self.chat_id,
            timeout=getattr(self.config, "TELEGRAM_TIMEOUT_SECONDS", 5.0),
            max_retries=getattr(self.config, "TELEGRAM_MAX_RETRIES", 2),
            backoff_seconds=getattr(self.config, "TELEGRAM_RETRY_BACKOFF_SECONDS", 1.0)
        )

        self.events_history: List[NotificationEvent] = []

        # Deduplication cache: key -> {"timestamp": datetime, "severity": str}
        self._alert_history: Dict[str, Dict[str, Any]] = {}

        # Delivery tracking
        self.delivery_channel = "NONE"
        if self.telegram_adapter.is_configured:
            self.delivery_channel = "TELEGRAM"
        elif self.webhook_url:
            self.delivery_channel = "WEBHOOK"

        self.delivery_status = "CONFIGURED — UNTESTED" if self.delivery_channel != "NONE" else "NOT CONFIGURED"
        self.last_delivery_timestamp: Optional[str] = None
        self.last_delivery_timestamp_sofia: Optional[str] = None
        self.last_attempt_timestamp: Optional[str] = None
        self.last_delivery_error: Optional[str] = None

    def _format_telegram_message(self, event: NotificationEvent) -> str:
        """Format an event into clean Telegram Markdown with severity emojis and timestamps."""
        severity_emojis = {
            "CRITICAL": "🚨",
            "ERROR": "❌",
            "WARNING": "⚠️",
            "INFO": "ℹ️"
        }
        emoji = severity_emojis.get(event.severity, "🔔")

        sofia_time = event.timestamp
        try:
            if sofia_time.tzinfo is None:
                sofia_time = sofia_time.replace(tzinfo=TIMEZONE_SOFIA)
            else:
                sofia_time = sofia_time.astimezone(TIMEZONE_SOFIA)
            time_str = sofia_time.strftime("%d %b %Y, %H:%M Sofia")
        except Exception:
            time_str = sofia_time.strftime("%Y-%m-%d %H:%M")

        lines = [
            f"{emoji} *[{event.severity}] {event.title}*",
            f"🕒 _{time_str}_",
            "",
            event.message
        ]
        return "\n".join(lines)

    def _should_suppress_alert(self, event: NotificationEvent) -> bool:
        """
        Check if an alert should be suppressed due to deduplication cooldown.
        Rules:
        - Severity escalation (e.g. WARNING -> CRITICAL) ALWAYS bypasses suppression.
        - Same or lower severity within cooldown window (e.g. 30 mins) is suppressed.
        """
        device_id = event.metadata.get("device_id", "global")
        key = f"{event.event_type}:{device_id}"

        if key not in self._alert_history:
            return False

        last_entry = self._alert_history[key]
        last_time = last_entry["timestamp"]
        last_sev = last_entry.get("severity", "INFO")

        # Severity ranking
        sev_rank = {"INFO": 1, "WARNING": 2, "ERROR": 3, "CRITICAL": 4}
        curr_rank = sev_rank.get(event.severity, 1)
        prev_rank = sev_rank.get(last_sev, 1)

        # 1. Escalation check: higher severity always bypasses cooldown
        if curr_rank > prev_rank:
            _LOGGER.info(
                f"Alert severity escalated from {last_sev} to {event.severity} for {key}; bypassing cooldown."
            )
            return False

        # 2. Cooldown check
        window_minutes = getattr(self.config, "ALERT_DEDUPLICATION_WINDOW_MINUTES", 30.0)
        now = datetime.now()
        if isinstance(last_time, str):
            try:
                last_time = datetime.fromisoformat(last_time)
            except Exception:
                last_time = now
        if last_time.tzinfo and not now.tzinfo:
            now = now.replace(tzinfo=last_time.tzinfo)
        elif now.tzinfo and not last_time.tzinfo:
            last_time = last_time.replace(tzinfo=now.tzinfo)

        elapsed_sec = (now - last_time).total_seconds()
        if elapsed_sec < (window_minutes * 60):
            _LOGGER.info(
                f"Duplicate alert suppressed by cooldown: {key} (last sent {elapsed_sec/60:.1f}m ago, window={window_minutes}m)"
            )
            return True

        return False

    def dispatch(self, event: NotificationEvent) -> None:
        """Route event to logging, audit file, and external channels (Telegram / Webhook)."""
        self.events_history.append(event)

        # 1. Console / CloudWatch Logging (Always scrub secrets)
        log_line = f"[{event.severity}] {event.title} - {event.message}"
        sanitized_log = redact_sensitive_str(log_line, self.bot_token)
        if event.severity == "CRITICAL":
            _LOGGER.critical(sanitized_log)
        elif event.severity == "ERROR":
            _LOGGER.error(sanitized_log)
        elif event.severity == "WARNING":
            _LOGGER.warning(sanitized_log)
        else:
            _LOGGER.info(sanitized_log)

        # 2. Append to audit file
        self._write_to_audit_file(event)

        # 3. Check deduplication suppression for external delivery
        if self._should_suppress_alert(event):
            return

        # 4. External Delivery (Telegram Bot API preferred, generic webhook fallback)
        now_dt = datetime.now()
        now_iso = now_dt.isoformat()
        try:
            now_sofia_str = now_dt.astimezone(TIMEZONE_SOFIA).strftime("%d %b %Y, %H:%M Sofia")
        except Exception:
            now_sofia_str = now_dt.strftime("%Y-%m-%d %H:%M")

        self.last_attempt_timestamp = now_iso

        try:
            if self.telegram_adapter and self.telegram_adapter.is_configured:
                # Deliver via Telegram Bot API
                telegram_text = self._format_telegram_message(event)
                success, err_msg = self.telegram_adapter.send_message(telegram_text)
                if success:
                    self.delivery_status = "LAST DELIVERY SUCCESSFUL"
                    self.last_delivery_timestamp = now_iso
                    self.last_delivery_timestamp_sofia = now_sofia_str
                    self.last_delivery_error = None
                    device_id = event.metadata.get("device_id", "global")
                    self._alert_history[f"{event.event_type}:{device_id}"] = {
                        "timestamp": now_dt,
                        "severity": event.severity
                    }
                else:
                    self.delivery_status = "DELIVERY FAILED"
                    self.last_delivery_error = err_msg
                    _LOGGER.warning(f"Telegram notification delivery failed: {err_msg}")

            elif self.webhook_url:
                # Deliver via generic webhook
                success, err_msg = self._send_webhook(event)
                if success:
                    self.delivery_status = "LAST DELIVERY SUCCESSFUL"
                    self.last_delivery_timestamp = now_iso
                    self.last_delivery_timestamp_sofia = now_sofia_str
                    self.last_delivery_error = None
                    device_id = event.metadata.get("device_id", "global")
                    self._alert_history[f"{event.event_type}:{device_id}"] = {
                        "timestamp": now_dt,
                        "severity": event.severity
                    }
                else:
                    self.delivery_status = "DELIVERY FAILED"
                    self.last_delivery_error = err_msg
                    _LOGGER.warning(f"Webhook notification delivery failed: {err_msg}")
            else:
                self.delivery_status = "NOT CONFIGURED"

        except Exception as e:
            # Guarantee delivery exceptions NEVER interrupt calling code or HVAC safety logic
            sanitized_err = redact_sensitive_str(str(e), self.bot_token)
            self.delivery_status = "DELIVERY FAILED"
            self.last_delivery_error = sanitized_err
            _LOGGER.warning(f"Notification dispatch encountered an exception: {sanitized_err}")

    def _write_to_audit_file(self, event: NotificationEvent) -> None:
        """Append structured JSON line to audit log."""
        try:
            log_file = AutomationConfig.AUDIT_LOG_FILE
            with open(log_file, "a", encoding="utf-8") as f:
                f.write(json.dumps(event.to_dict()) + "\n")
        except Exception as e:
            _LOGGER.warning(f"Failed to append to audit log file: {e}")

    def _send_webhook(self, event: NotificationEvent) -> Tuple[bool, Optional[str]]:
        """Send event payload to external webhook, with automatic formatting for legacy Telegram/Discord."""
        if not self.webhook_url:
            return (False, "Webhook URL not configured")

        sanitized_url = "[REDACTED_WEBHOOK_URL]"
        try:
            if "api.telegram.org" in self.webhook_url:
                parsed_url = urllib.parse.urlparse(self.webhook_url)
                query_params = urllib.parse.parse_qs(parsed_url.query)
                chat_id = query_params.get("chat_id", [None])[0]
                text = f"*{event.severity}*: *{event.title}*\n{event.message}"
                payload_dict = {"text": text, "parse_mode": "Markdown"}
                if chat_id:
                    payload_dict["chat_id"] = chat_id
                payload = json.dumps(payload_dict).encode("utf-8")
            elif "discord.com" in self.webhook_url:
                payload = json.dumps({
                    "content": f"**[{event.severity}] {event.title}**\n{event.message}"
                }).encode("utf-8")
            else:
                payload = json.dumps({
                    "source": "TCL-Airbnb-HVAC-Automation",
                    "event": event.to_dict()
                }).encode("utf-8")

            req = urllib.request.Request(
                self.webhook_url,
                data=payload,
                headers={"Content-Type": "application/json"}
            )
            with http_transport.open_https(req, timeout=5) as resp:
                if resp.status >= 400:
                    err_msg = f"Webhook returned HTTP {resp.status}"
                    _LOGGER.warning(f"Webhook {sanitized_url} returned HTTP {resp.status}")
                    return (False, err_msg)
                return (True, None)
        except Exception as e:
            err_msg = f"Webhook request failed ({type(e).__name__})"
            _LOGGER.warning(f"Failed to dispatch notification to webhook {sanitized_url}: {err_msg}")
            return (False, err_msg)

    def get_delivery_state(self) -> Dict[str, Any]:
        """Export serializable notification delivery state for S3 persistence."""
        return {
            "status": self.delivery_status,
            "channel": self.delivery_channel,
            "configured": (self.delivery_status != "NOT CONFIGURED"),
            "last_delivery_timestamp": self.last_delivery_timestamp,
            "last_delivery_timestamp_sofia": self.last_delivery_timestamp_sofia,
            "last_attempt_timestamp": self.last_attempt_timestamp,
            "last_delivery_error": self.last_delivery_error,
            "alert_history": {
                k: {
                    "timestamp": v["timestamp"].isoformat() if isinstance(v.get("timestamp"), datetime) else v.get("timestamp"),
                    "severity": v.get("severity")
                }
                for k, v in self._alert_history.items()
            }
        }

    def set_delivery_state(self, state: Dict[str, Any]) -> None:
        """Hydrate notification delivery state from S3 persistence across Lambda cold starts."""
        if not state or not isinstance(state, dict):
            return

        # Restore status if currently configured
        if self.delivery_channel != "NONE":
            persisted_status = state.get("status")
            if persisted_status in ("LAST DELIVERY SUCCESSFUL", "DELIVERY FAILED", "CONFIGURED — UNTESTED"):
                self.delivery_status = persisted_status

        self.last_delivery_timestamp = state.get("last_delivery_timestamp")
        self.last_delivery_timestamp_sofia = state.get("last_delivery_timestamp_sofia")
        self.last_attempt_timestamp = state.get("last_attempt_timestamp")
        self.last_delivery_error = state.get("last_delivery_error")

        # Hydrate alert history for deduplication
        raw_hist = state.get("alert_history", {})
        if isinstance(raw_hist, dict):
            for k, v in raw_hist.items():
                if isinstance(v, dict) and "timestamp" in v:
                    try:
                        ts = datetime.fromisoformat(v["timestamp"])
                        self._alert_history[k] = {"timestamp": ts, "severity": v.get("severity", "INFO")}
                    except Exception:
                        pass

