    def notify_frost_warning(
        self,
        device_id: str,
        measured_temp: float,
        threshold: float,
        severity: str = "WARNING",
        is_guest_disabled: bool = True,
        is_stale: bool = False,
        reading_age_str: Optional[str] = None,
        measured_at_str: Optional[str] = None,
        metadata: Optional[Dict] = None
    ) -> None:
        room_label = format_device_label(device_id, self.config)
        meta = metadata or {}
        meta.update({
            "device_id": device_id,
            "measured_temperature": measured_temp,
            "threshold": threshold,
            "is_guest_disabled": is_guest_disabled,
            "is_stale": is_stale,
            "reading_age_str": reading_age_str,
            "measured_at_str": measured_at_str
        })
        guest_note = (
            " The unit is currently turned OFF by guest preference. "
            "Automation has preserved the guest power-OFF override to respect guest choices and privacy. "
            "Host escalation: please contact the guest directly to verify comfort and window status."
            if is_guest_disabled else ""
        )
        stale_prefix = "[STALE TELEMETRY] " if is_stale else ""
        stale_note = (
            f" (NOTE: Sensor measurement is STALE — recorded {reading_age_str} ago at {measured_at_str}. "
            f"Actual room conditions may be significantly colder!)"
            if is_stale and reading_age_str else ""
        )
        self.dispatch(NotificationEvent(
            event_type="FROST_WARNING",
            title=f"{stale_prefix}Low Indoor Temperature Alert: {room_label} ({measured_temp}°C)",
            message=(
                f"Indoor temperature on {room_label} is {measured_temp}°C (below threshold {threshold}°C)."
                f"{stale_note}"
                f"{guest_note}"
            ),
            severity=severity,
            metadata=meta
        ))

    def notify_stale_telemetry_warning(
        self,
        device_id: str,
        age_hours: float,
        last_temp: Optional[float],
        is_guest_disabled: bool = True,
        is_offline: bool = False,
        metadata: Optional[Dict] = None
    ) -> None:
        room_label = format_device_label(device_id, self.config)
        meta = metadata or {}
        meta.update({
            "device_id": device_id,
            "age_hours": age_hours,
            "last_temperature": last_temp,
            "is_guest_disabled": is_guest_disabled,
            "is_offline": is_offline
        })
        status_desc = "offline" if is_offline else ("turned OFF by guest (unventilated standby)" if is_guest_disabled else "running")
        last_temp_str = f"{last_temp}°C" if last_temp is not None else "unknown"
        self.dispatch(NotificationEvent(
            event_type="TELEMETRY_STALE_WARNING",
            title=f"Stale Sensor Telemetry Alert: {room_label} ({age_hours:.1f}h inactive)",
            message=(
                f"Indoor temperature sensor on {room_label} has not transmitted an update for {age_hours:.1f} hours "
                f"(device status: {status_desc}). Last recorded reading: {last_temp_str}. "
                f"Because the unit is unventilated, temperature cannot be guaranteed. Monitor property conditions."
            ),
            severity="WARNING",
            metadata=meta
        ))

    def notify_economic_alert(
        self,
        device_id: str,
        requested_temp: float,
        measured_temp: Optional[float],
        limit: float,
        reason: str,
        severity: str = "INFO",
        metadata: Optional[Dict] = None
    ) -> None:
        room_label = format_device_label(device_id, self.config)
        meta = metadata or {}
        meta.update({
            "device_id": device_id,
            "requested_temp": requested_temp,
            "measured_temp": measured_temp,
            "economic_limit": limit,
            "reason": reason,
        })
        meas_str = f" (measured room temp: {measured_temp}°C)" if measured_temp is not None else ""
        self.dispatch(NotificationEvent(
            event_type="ECONOMIC_ALERT",
            title=f"Economic Policy Notice: {room_label} ({requested_temp}°C)",
            message=(
                f"Guest requested {requested_temp}°C on {room_label}{meas_str}, exceeding recommended limit ({limit}°C). "
                f"Assessment: {reason}"
            ),
            severity=severity,
            metadata=meta
        ))
